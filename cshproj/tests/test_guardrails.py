def _records(question: str) -> list[dict]:
    from app import demo
    rows, _ = demo.filter_records(question)
    return [{"name": w["name"],
             "defaulter_matched": w["defaulter_matched"],
             "health_arrears_matched": w["health_arrears_matched"]} for w in rows]


def main() -> None:
    failed = []

    print(f"차단 케이스 {len(BLOCK)}건")
    for text, expected in BLOCK:
        verdict = guardrails.inspect(text)
        ok = verdict.blocked and expected in verdict.rule_ids
        if not ok:
            failed.append(("차단 실패", text, verdict.rule_ids, expected))
        print(f"  {'OK ' if ok else '실패'} {text[:52]:<54} {','.join(verdict.rule_ids)}")

    print(f"\n통과 케이스 {len(ALLOW)}건")
    for text in ALLOW:
        verdict = guardrails.inspect(text)
        if verdict.blocked:
            failed.append(("오탐", text, verdict.rule_ids, "-"))
        print(f"  {'OK ' if not verdict.blocked else '오탐'} {text[:52]:<54} {','.join(verdict.rule_ids)}")

    print(f"\n데이터 대조 {len(FACTS)}건")
    for question, answer, should_block in FACTS:
        verdict = guardrails.inspect(answer, _records(question), question)
        ok = verdict.blocked == should_block
        if not ok:
            failed.append(("대조 실패", answer, verdict.rule_ids,
                           "차단" if should_block else "통과"))
        want = "차단" if should_block else "통과"
        print(f"  {'OK ' if ok else '실패'} [{want}] {answer[:44]:<46} {','.join(verdict.rule_ids)}")

    total = len(BLOCK) + len(ALLOW) + len(FACTS)
    print(f"\n총 {total}건 · 실패 {len(failed)}건")
    for kind, text, got, want in failed:
        print(f"  [{kind}] {text}\n         기대 {want} / 실제 {got}")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
