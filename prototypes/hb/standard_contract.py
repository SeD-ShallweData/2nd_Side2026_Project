def guide_for(field_key):
    """항목 key로 작성 가이드를 조회. 없으면 None."""
    return STANDARD_FIELDS.get(field_key)


def guide_block(field_keys):
    """여러 항목의 작성 가이드를 프롬프트용 텍스트로 만든다."""
    parts = []
    for key in field_keys:
        g = STANDARD_FIELDS.get(key)
        if not g:
            continue
        parts.append(
            f"- {g['label']} (근거: {g['legal_basis']})\n"
            f"  표준서식 기재 양식: {g['template']}\n"
            f"  기재 방법: {g['how']}"
        )
    return "\n".join(parts)
