# ── 조회 도우미 ───────────────────────────────────────────────────────
def min_wage(year: int | None = None) -> dict:
    """해당 연도 최저임금. 표에 없는 연도는 가장 최근 값으로 대체합니다."""
    year = year or date.today().year
    return MIN_WAGE.get(year) or MIN_WAGE[LATEST_MIN_WAGE_YEAR]


def min_wage_year(year: int | None = None) -> int:
    year = year or date.today().year
    return year if year in MIN_WAGE else LATEST_MIN_WAGE_YEAR


def law(key: str) -> dict:
    """조문 조회. 없는 키를 요구하면 바로 터뜨립니다 — 조문을 지어내는 것보다 낫습니다."""
    try:
        return LAWS[key]
    except KeyError:
        raise KeyError(f"조문 표에 없는 키입니다: {key}. standards.LAWS 에 먼저 추가하세요.") from None


def monthly_scheduled_hours(weekly_hours: float) -> float:
    """주 소정근로시간 → 월 소정근로시간(유급 주휴 포함).

    주휴시간은 통상근로자(주 40시간)에 비례해 계산합니다.
      주 40시간 → (40 + 8) × 4.345 ≒ 208.6  (고시 환산 209시간)
      주 20시간 → (20 + 4) × 4.345 ≒ 104.3

    주 15시간 미만은 주휴수당이 발생하지 않으므로 주휴시간을 더하지 않습니다.
    """
    if weekly_hours <= 0:
        return 0.0
    paid_weekly_holiday = (weekly_hours / LEGAL_WEEKLY_HOURS) * 8 if weekly_hours >= 15 else 0.0
    return round((weekly_hours + paid_weekly_holiday) * WEEKS_PER_MONTH, 1)


def required_break_minutes(daily_hours: float) -> int:
    """1일 근로시간에 대한 법정 최소 휴게시간(분)."""
    for threshold, minutes in BREAK_TABLE:
        if daily_hours >= threshold:
            return minutes
    return 0


def is_simple_labor(job: str | None) -> bool:
    """단순노무업무인가 — 수습 감액이 아예 불가능한 직무."""
    if not job:
        return False
    return any(word in job for word in SIMPLE_LABOR_KEYWORDS)
